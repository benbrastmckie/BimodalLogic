#!/usr/bin/env python3
"""Measure the structural partitions the publication refactor programme depends on.

Every number in ``docs/development/PUBLICATION_REFACTOR.md`` and in ADR-011 is
regenerated by this script, never typed.  It reads the live tree through
``scripts/lib/import_graph.py`` (leading-import parse, archive excluded by
directory name) and prints markdown tables, or JSON with ``--json``.

Usage (run from the repository root):

  measure-refactor-partitions.py upward-edges
  measure-refactor-partitions.py weakcanonical-partition
  measure-refactor-partitions.py automation-partition
  measure-refactor-partitions.py namespace-audit
  measure-refactor-partitions.py all
  measure-refactor-partitions.py --check      # exit 1 if the Expressiveness set leaks

The four measurements:

  upward-edges             Every import that runs *up* the layer stack recorded
                           in ORGANISATION.md (Syntax/ProofSystem/ForMathlib=0,
                           Semantics=1, Metalogic=2, Theorems=3, Automation=4,
                           Examples=5), grouped by source and target directory,
                           with the Theorems <-> Metalogic pair called out.
  weakcanonical-partition  Each module under Metalogic/WeakCanonical/ classified
                           by whether BXCanonical is in its transitive closure;
                           the proposed Expressiveness set (EXPRESSIVENESS_SET
                           below) with its file and line counts, the residual
                           set, and every edge from the Expressiveness set into
                           the residual or into BXCanonical (expected: none).
  automation-partition     The Automation modules the *library* needs -- the
                           union of the closures of every non-Automation
                           library module, with Examples/, MainResults and the
                           tooling-only TraceExport pruned from the walk --
                           against the complement, which is dataset/ML tooling.
  namespace-audit          Each live file's first `namespace` against its
                           module path: equal-or-descendant, ancestor, unrelated
                           or none.

``--check`` is the pre-move gate for the Expressiveness extraction: it exits 0
only when the Expressiveness set has no edge into the residual WeakCanonical
set and none into BXCanonical.  Never weaken it; if it fails, the offending
edges are the work, and the relocation has to be dependency-first.

Measured on commit 220e94ea4 (the tree the programme was written against):
  upward-edges              16 import lines from the five lower layers into
                            Automation, 11 of them into the attribute-only
                            files TruthNormAttr and LemmaDB (the programme's
                            source analysis had said 17 and 12; the script is
                            right); 4 Theorems files import
                            Metalogic.Core.DeductionTheorem; 29 Metalogic files
                            import Theorems across 47 lines
  weakcanonical-partition   Expressiveness 141 files / 104,087 lines,
                            residual 38 files / 28,472 lines, 0 leaking edges;
                            BXCanonical-free by closure: 150 of 179
  automation-partition      9 library-needed modules (3,419 lines), 4
                            user-facing tactic modules (1,238), 25 tooling
                            modules including TraceExport (14,747)
  namespace-audit           279 equal-or-descendant / 187 ancestor / 24
                            unrelated / 43 with no namespace; 15 of the 24 are
                            the {Plus,Minus,Star}Language files (not 17)
Where a document and this output disagree, this output is right; the document
records the discrepancy rather than the other way round.
"""

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "lib"))
from import_graph import ImportGraph, first_namespace  # noqa: E402

LIB = "FormalSystem"

# ORGANISATION.md's layer table.  A top-level module such as `FormalSystem.Init`
# or `FormalSystem.MainResults` has no layer and never contributes an edge.
LAYERS = {
    "Syntax": 0, "ProofSystem": 0, "ForMathlib": 0, "Init": 0,
    "Semantics": 1,
    "Metalogic": 2,
    "Theorems": 3,
    "Automation": 4,
    "Examples": 5,
}

WEAK = f"{LIB}.Metalogic.WeakCanonical"
BX = f"{LIB}.Metalogic.BXCanonical"

# The proposed Metalogic/Expressiveness/ set, named relative to WeakCanonical/.
# A name is a subtree (every module below it) or a single module.
EXPRESSIVENESS_SET = (
    "Kamp", "EFGames", "Expressiveness", "Separation",
    "NormalForm", "MonadicFO", "StaviConnectives",
    "PriorDefs", "PriorDefsDense", "PriorExpressiveness", "PriorExpressivenessDense",
    "Table", "EFGameTactics",
)

# User-facing tactic modules: library API that no library file imports (a user
# does), so the closure walk cannot see them.  Classified as library, not tooling.
USER_FACING_TACTICS = frozenset(
    f"{LIB}.Automation.Tactics.{n}" for n in ("Commands", "Deduction", "Search", "UserTactics")
)

# Pruned from the automation-partition walk: these import Automation on purpose
# (Examples imports the whole aggregator; MainResults audits everything;
# TraceExport is tooling whose only consumer is an exe root).
AUTOMATION_PRUNE_PREFIXES = (f"{LIB}.Examples",)
AUTOMATION_PRUNE_MODULES = (
    f"{LIB}.Examples",
    f"{LIB}.MainResults",
    f"{LIB}.Metalogic.Decidability.TraceExport",
    f"{LIB}.Automation",          # the aggregator imports every Automation module
    f"{LIB}.FormalSystem",        # the two roots import the aggregator
    LIB,
)


def top_dir(module):
    parts = module.split(".")
    return parts[1] if len(parts) > 1 and parts[0] == LIB else None


def layer_of(module):
    d = top_dir(module)
    return LAYERS.get(d) if d else None


def md_table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


# ---------------------------------------------------------------------------
# upward-edges
# ---------------------------------------------------------------------------

def measure_upward_edges(g):
    lib_modules = [m for m in g.modules if m.startswith(LIB + ".")]
    edges = []  # (src_module, tgt_module)
    for src in lib_modules:
        ls = layer_of(src)
        if ls is None:
            continue
        for tgt in g.edges[src]:
            lt = layer_of(tgt)
            if lt is None or lt <= ls:
                continue
            edges.append((src, tgt))
    classes = {}
    for src, tgt in edges:
        classes.setdefault((top_dir(src), top_dir(tgt)), []).append((src, tgt))
    into_automation = [(s, t) for s, t in edges if top_dir(t) == "Automation"
                       and top_dir(s) in ("Syntax", "Semantics", "ProofSystem", "Theorems", "Metalogic")]
    # Both directions of the Theorems <-> Metalogic pair are computed directly
    # rather than read off `edges`: the table puts Metalogic (2) below Theorems
    # (3), so only Metalogic -> Theorems counts as "upward" above, while the
    # reverse direction is what the table calls downward and is invisible there.
    theorems_to_metalogic = sorted({s for s in lib_modules if top_dir(s) == "Theorems"
                                    for t in g.edges[s] if top_dir(t) == "Metalogic"})
    metalogic_to_theorems = sorted({s for s in lib_modules if top_dir(s) == "Metalogic"
                                    for t in g.edges[s] if top_dir(t) == "Theorems"})
    return {
        "edge_count": len(edges),
        "into_automation_line_count": len(into_automation),
        "classes": {f"{a} -> {b}": sorted(v) for (a, b), v in sorted(classes.items())},
        "theorems_files_importing_metalogic": theorems_to_metalogic,
        "metalogic_files_importing_theorems": metalogic_to_theorems,
    }


def print_upward_edges(r):
    print("## Upward edges (source layer below target layer per ORGANISATION.md)\n")
    print(f"Total upward import lines: {r['edge_count']} "
          f"({r['into_automation_line_count']} from the five lower layers into Automation)\n")
    for cls, pairs in r["classes"].items():
        print(f"### {cls} ({len(pairs)} lines)\n")
        print(md_table(["Source module", "Imports"], pairs))
        print()
    print(f"### Theorems <-> Metalogic\n")
    print(f"- Theorems files importing Metalogic: {len(r['theorems_files_importing_metalogic'])}")
    for m in r["theorems_files_importing_metalogic"]:
        print(f"  - `{m}`")
    print(f"- Metalogic files importing Theorems: {len(r['metalogic_files_importing_theorems'])}")
    print()


