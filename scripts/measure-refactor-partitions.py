def measure_automation(g):
    auto_prefix = f"{LIB}.Automation."
    automation = sorted(m for m in g.modules if m.startswith(auto_prefix))
    prune = set(AUTOMATION_PRUNE_MODULES) | {
        m for m in g.modules if any(m == p or m.startswith(p + ".") for p in AUTOMATION_PRUNE_PREFIXES)
    }
    roots = [m for m in g.modules
             if m.startswith(LIB + ".") and not m.startswith(auto_prefix) and m not in prune]
    needed = set()
    needed_by = {}
    for r in roots:
        for c in g.closure(r, exclude=frozenset(prune)):
            if c.startswith(auto_prefix):
                needed.add(c)
                # record direct importers only, for the table
        for t in g.edges[r]:
            if t.startswith(auto_prefix):
                needed_by.setdefault(t, set()).add(r)
    needed = sorted(needed)
    user_facing = sorted(m for m in automation if m in USER_FACING_TACTICS)
    tooling = sorted(m for m in automation if m not in set(needed) and m not in USER_FACING_TACTICS)
    tooling.append(f"{LIB}.Metalogic.Decidability.TraceExport")
    tooling.sort()
    exe_roots = sorted(m for m in tooling if m.endswith("Main"))
    tests_importing_tooling = {}
    for m in g.modules:
        if not m.startswith("BimodalTest"):
            continue
        hits = [t for t in g.edges[m] if t in set(tooling)]
        if hits:
            tests_importing_tooling[m] = hits

    def lines(ms):
        return sum(g.line_count(m) for m in ms)

    return {
        "library_needed": {"count": len(needed), "lines": lines(needed), "modules": needed,
                           "direct_importers": {k: sorted(v) for k, v in sorted(needed_by.items())}},
        "user_facing_tactics": {"count": len(user_facing), "lines": lines(user_facing),
                                "modules": user_facing},
        "tooling": {"count": len(tooling), "lines": lines(tooling), "modules": tooling,
                    "exe_roots": exe_roots},
        "tests_importing_tooling": tests_importing_tooling,
        "pruned_roots": sorted(prune & set(g.modules)),
    }


def print_automation(r):
    n, u, t = r["library_needed"], r["user_facing_tactics"], r["tooling"]
    print("## Automation partition\n")
    print(md_table(["Set", "Modules", "Lines"],
                   [("Library-needed Automation modules (by closure)", n["count"], f"{n['lines']:,}"),
                    ("User-facing tactic modules (library API, imported by no library file)",
                     u["count"], f"{u['lines']:,}"),
                    ("Tooling (dataset / ML / benchmark / exe roots, plus TraceExport)",
                     t["count"], f"{t['lines']:,}")]))
    print()
    print("### Library-needed modules and their direct importers outside Automation\n")
    rows = []
    for m in n["modules"]:
        imps = n["direct_importers"].get(m, [])
        rows.append((f"`{m}`", len(imps), ", ".join(f"`{i}`" for i in imps[:4]) + (" ..." if len(imps) > 4 else "")))
    print(md_table(["Module", "Direct importers", "Examples"], rows))
    print()
    print("### Tooling modules\n")
    for m in t["modules"]:
        print(f"- `{m}`" + ("  (exe root)" if m in t["exe_roots"] else ""))
    print()
    print(f"### Test files importing tooling modules: {len(r['tests_importing_tooling'])}\n")
    for m, hits in sorted(r["tests_importing_tooling"].items()):
        print(f"- `{m}` -> " + ", ".join(f"`{h}`" for h in hits))
    print()
    print("Pruned from the walk: " + ", ".join(f"`{m}`" for m in r["pruned_roots"] if not m.startswith(LIB + ".Examples."))
          + f" and every module under `{LIB}.Examples`.\n")


