def in_expressiveness_set(module):
    rel = module[len(WEAK) + 1:]
    head = rel.split(".")[0]
    return head in EXPRESSIVENESS_SET


def measure_weakcanonical(g):
    members = g.under(WEAK)
    aggregator = WEAK if WEAK in members else None
    modules = [m for m in members if m != WEAK]
    expr = sorted(m for m in modules if in_expressiveness_set(m))
    resid = sorted(m for m in modules if not in_expressiveness_set(m))
    expr_set, resid_set = set(expr), set(resid)

    def bx_free(m):
        return not any(c == BX or c.startswith(BX + ".") for c in g.closure(m))

    pure = sorted(m for m in modules if bx_free(m))
    impure = sorted(m for m in modules if m not in set(pure))

    leaks = []
    for m in expr:
        for t in g.edges[m]:
            if t in resid_set or t == BX or t.startswith(BX + "."):
                leaks.append((m, t))
    importers_outside = {}
    for m in expr:
        for src in g.reverse.get(m, ()):
            if src not in expr_set:
                importers_outside.setdefault(src, []).append(m)

    def lines(ms):
        return sum(g.line_count(m) for m in ms)

    subtree_rows = []
    for name in EXPRESSIVENESS_SET:
        ms = [m for m in expr if m[len(WEAK) + 1:].split(".")[0] == name]
        subtree_rows.append((name, len(ms), lines(ms)))

    return {
        "aggregator": aggregator,
        "module_count": len(modules),
        "expressiveness": {"files": len(expr), "lines": lines(expr), "modules": expr,
                           "subtrees": subtree_rows},
        "residual": {"files": len(resid), "lines": lines(resid), "modules": resid},
        "bxcanonical_free_by_closure": {"pure": len(pure), "impure": len(impure),
                                        "impure_modules": impure},
        "expressiveness_not_bx_free": sorted(m for m in expr if m not in set(pure)),
        "leaking_edges": leaks,
        "importers_outside_set": {k: sorted(v) for k, v in sorted(importers_outside.items())},
    }


def print_weakcanonical(r):
    e, s = r["expressiveness"], r["residual"]
    print("## WeakCanonical partition\n")
    print(f"Modules under `Metalogic/WeakCanonical/`: {r['module_count']}"
          + (f" (plus the sibling aggregator `{r['aggregator']}`, not counted)" if r["aggregator"] else "") + "\n")
    print(md_table(["Set", "Files", "Lines"],
                   [("Expressiveness (proposed move)", e["files"], f"{e['lines']:,}"),
                    ("Residual WeakCanonical", s["files"], f"{s['lines']:,}")]))
    print()
    print("### Expressiveness set by subtree\n")
    print(md_table(["Name (relative to WeakCanonical/)", "Files", "Lines"],
                   [(n, f, f"{l:,}") for n, f, l in e["subtrees"]]))
    print()
    p = r["bxcanonical_free_by_closure"]
    print(f"BXCanonical-free by transitive closure: {p['pure']} of {r['module_count']} "
          f"({p['impure']} reach BXCanonical)\n")
    if r["expressiveness_not_bx_free"]:
        print("Expressiveness modules that reach BXCanonical (MUST be empty):")
        for m in r["expressiveness_not_bx_free"]:
            print(f"- `{m}`")
        print()
    print(f"### Edges from the Expressiveness set into the residual set or BXCanonical: "
          f"{len(r['leaking_edges'])}\n")
    for src, tgt in r["leaking_edges"]:
        print(f"- `{src}` -> `{tgt}`")
    if r["leaking_edges"]:
        print()
    print("### Importers of the Expressiveness set from outside it\n")
    for src, tgts in r["importers_outside_set"].items():
        print(f"- `{src}` ({len(tgts)} line{'s' if len(tgts) != 1 else ''})")
    print()
    print("### Residual modules\n")
    for m in s["modules"]:
        print(f"- `{m}`")
    print()


