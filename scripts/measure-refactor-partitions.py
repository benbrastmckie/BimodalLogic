def classify_namespace(dir_module, ns):
    """Compare a file's first namespace with its *directory* module.

    `Syntax/Formula.lean` has directory module `FormalSystem.Syntax`; a
    namespace equal to that, or below it, is the Mathlib-usual shape
    ("equal-or-descendant").  A namespace strictly above it ("ancestor") is
    Mathlib-acceptable.  Anything else is "unrelated" -- the file lives
    somewhere its namespace does not say.
    """
    if ns is None:
        return "none"
    if ns == dir_module or ns.startswith(dir_module + "."):
        return "equal-or-descendant"
    if dir_module.startswith(ns + "."):
        return "ancestor"
    return "unrelated"


def measure_namespaces(g):
    buckets = {"equal-or-descendant": [], "ancestor": [], "unrelated": [], "none": []}
    for m, p in g.modules.items():
        if not m.startswith(LIB + "."):
            continue
        ns = first_namespace(p)
        dir_module = m.rsplit(".", 1)[0]
        buckets[classify_namespace(dir_module, ns)].append((m, ns))
    return {k: {"count": len(v), "entries": sorted(v, key=lambda x: x[0])} for k, v in buckets.items()}


def print_namespaces(r):
    print("## Namespace audit (first `namespace` vs directory module, library files only)\n")
    print(md_table(["Bucket", "Files"], [(k, v["count"]) for k, v in r.items()]))
    print()
    print("### Unrelated\n")
    print(md_table(["Module", "First namespace"], [(f"`{m}`", f"`{ns}`") for m, ns in r["unrelated"]["entries"]]))
    print()


