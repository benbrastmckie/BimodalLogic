MODES = {
    "upward-edges": (measure_upward_edges, print_upward_edges),
    "weakcanonical-partition": (measure_weakcanonical, print_weakcanonical),
    "automation-partition": (measure_automation, print_automation),
    "namespace-audit": (measure_namespaces, print_namespaces),
}


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0],
                                 formatter_class=argparse.RawDescriptionHelpFormatter,
                                 epilog="\n".join(__doc__.split("\n\n")[1:]))
    ap.add_argument("mode", nargs="?", choices=sorted(MODES) + ["all"],
                    help="which measurement to print (default: all, or none with --check)")
    ap.add_argument("--json", action="store_true", help="emit JSON instead of markdown")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the Expressiveness set has any edge into the residual "
                         "WeakCanonical set or into BXCanonical")
    args = ap.parse_args(argv)
    if not os.path.isdir(LIB):
        print(f"measure-refactor-partitions.py: no {LIB}/ directory; run from the repository root",
              file=sys.stderr)
        return 2

    g = ImportGraph()
    modes = list(MODES) if args.mode in (None, "all") else [args.mode]
    if args.check and args.mode is None:
        modes = []

    try:
        results = {m: MODES[m][0](g) for m in modes}
    except UnlayeredModuleError as e:
        print(f"measure-refactor-partitions.py: {e}", file=sys.stderr)
        return 1
    if args.json:
        print(json.dumps(results, indent=2))
    else:
        for m in modes:
            MODES[m][1](results[m])

    if args.check:
        r = results.get("weakcanonical-partition") or measure_weakcanonical(g)
        bad = r["leaking_edges"]
        not_free = r["expressiveness_not_bx_free"]
        # An empty Expressiveness set makes every assertion below vacuously true.
        # ADR-011 promises this check is "a standing pre-move gate"; without this
        # branch it would degenerate to a permanent PASS the moment either root
        # stopped resolving.  Fail loudly instead.
        if not r["expressiveness"]["files"] or not r["residual"]["files"]:
            print(f"FAIL  degenerate partition: Expressiveness set has "
                  f"{r['expressiveness']['files']} file(s) and the residual WeakCanonical set has "
                  f"{r['residual']['files']} file(s); neither may be empty.")
            print(f"      Expressiveness root: {EXPR}")
            print(f"      residual root:       {WEAK}")
            print("      An empty set makes the leak assertion vacuous. Re-point the roots "
                  "rather than accepting the PASS.")
            return 1
        if bad or not_free:
            print(f"FAIL  Expressiveness set leaks: {len(bad)} edge(s) into residual/BXCanonical, "
                  f"{len(not_free)} module(s) reach BXCanonical by closure")
            for s, t in bad:
                print(f"      {s} -> {t}")
            for m in not_free:
                print(f"      closure: {m}")
            return 1
        print(f"PASS  Expressiveness set ({r['expressiveness']['files']} files) has no edge into the "
              f"residual WeakCanonical set ({r['residual']['files']} files) or BXCanonical")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
