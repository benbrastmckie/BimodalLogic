#!/usr/bin/env python3
"""Per-root `env_linter` ceiling for the C16-roots signal: parser, `--update` writer, and the
default compare-mode gate `scripts/check-module-invariants.sh`'s C16 second half calls.

C16's first half runs `lake exe runLinter FormalSystem` against `scripts/nolints.json` and is
already enforced. Its second half widens the SAME linter batch to every other lakefile root
(`python3 scripts/lake_targets.py exe-roots` + `lib-roots`, minus `FormalSystem`) because
`runLinter <Module>` observes a package by IMPORTING it, so every out-of-closure root's findings
are invisible to the first half by construction. This script is the generator AND the gate for
that widened scope, on the `scripts/warning-budget.py` model: the SAME code parses a sweep's logs
whether writing the baseline or checking against it, so the two can never disagree about key
shape.

Baseline key: `<count> <root> <module> <linter>`. The root is part of the key because a module
reachable from two roots is counted once per root -- that is how the gate's own per-root sum is
formed. No line number is recorded, deliberately: an unrelated edit above a finding would
otherwise manufacture a new one.

NEVER regenerate scripts/c16-roots-baseline.txt to make a genuine regression disappear.
`--update` rewrites it wholesale from the logs it is handed and would bless a regression along
with everything else -- the same failure mode C16's own header warns about for
scripts/nolints.json. The counts are a CEILING and may only decrease.

Disposition rows, the `scripts/warning-budget.py` model: every linter class observed in a sweep
MUST have a `# disposition <linter> <blocking|advisory|pending>` row. A class with no row is
exit 2, never a silent pass -- the guard that stops a future linter class being absorbed into
the baseline by a routine `--update` with nobody reading it. `pending` means nobody has read the
class yet; the gate may not ship enforced while any row still reads it.

Usage (run from the repository root):
  c16_roots_baseline.py --log-dir DIR            verify the logs in DIR against the baseline
  c16_roots_baseline.py --log-dir DIR --update   rewrite the baseline from the logs in DIR
  c16_roots_baseline.py --log-dir DIR --list     current per-root counts, highest first

Each root's log at `<DIR>/<root>.log` is expected to be the raw stdout+stderr of
`lake exe runLinter <root>` (useErrorFormat, groupByFilename -- Batteries' own default `main`
behavior), i.e. the SAME invocation the C16-roots gate makes. The root list itself comes from
the single existing scrape site, `python3 scripts/lake_targets.py exe-roots` + `lib-roots`,
minus `FormalSystem`, so this script and every other per-root sweep in this repository agree on
what "every root" means without either hand-maintaining a list.

Exit status:
  0  every (root, module, linter) row's live count is <= its baseline ceiling (or a successful
     --list/--update)
  1  at least one row's live count exceeds its baseline ceiling, or is a non-zero count absent
     from the baseline entirely (a root/module newly introducing the defect class)
  2  the measurement itself could not be trusted (a root's log is missing, or unparseable --
     neither a `-- Found N error(s)` nor a `-- Linting passed for` line is present), an
     undispositioned linter class was observed, or a disposition row still reads `pending` --
     NEVER silently treated as "no findings". Silence must never read as success, the
     ENFORCE_C28=0 precedent. EXCEPTION: a root named in scripts/c16-roots-unmeasurable.txt
     (the scripts/module-invariants-manifest.txt/C6 precedent) is excused from THIS arm when
     its own log is the thing that could not be trusted -- its exclusion is still reported, on
     every run, via an INFO line to stderr, never silently dropped.
"""

import argparse
import os
import re
import subprocess
import sys

BASELINE_NAME = os.path.join("scripts", "c16-roots-baseline.txt")
UNMEASURABLE_NAME = os.path.join("scripts", "c16-roots-unmeasurable.txt")
DISPOSITIONS = ("blocking", "advisory", "pending")

LINTER_HEADER_RE = re.compile(r"^/- The `([^`]+)` linter reports:$")
MODULE_HEADER_RE = re.compile(r"^-- (\S+)$")
ERROR_LINE_RE = re.compile(r"^\S.*\.lean:\d+:\d+: error: ")
FOUND_RE = re.compile(r"^-- Found \d+ errors? ")
PASSED_RE = re.compile(r"^-- Linting passed for ")

HEADER = """\
# scripts/c16-roots-baseline.txt -- pinned env_linter ceilings over every non-FormalSystem
# lakefile root (C16's second half; the first half is scripts/nolints.json).
#
# Generated by `python3 scripts/c16_roots_baseline.py --log-dir DIR --update`. Each entry is
# `<count> <root> <module> <linter>`. A module reachable from two roots is counted once per
# root, which is why the root is part of the key -- that is how the gate's own per-root sum is
# formed. No line number is recorded, deliberately: an unrelated edit above a finding would
# otherwise manufacture a new one.
#
# THE COUNTS ARE A CEILING AND MAY ONLY DECREASE. Never regenerate this file to make a genuine
# regression disappear -- `--update` rewrites it wholesale from the handed-in logs and would
# bless the regression along with everything else, exactly the failure mode C16's own header
# warns about for scripts/nolints.json. To retire a finding, fix it and let `--update` show the
# count dropping in the same commit as the fix, with the diff visible.
#
# Every linter class observed in a sweep MUST have a disposition row below. A class with no row
# is exit 2, not a silent pass -- that guard is what stops a future linter class being absorbed
# into this baseline by a routine --update without anyone reading it.
#
# Dispositions: blocking | advisory | pending
#   blocking  a finding of this class fails the gate when its (root, module) count rises
#   advisory  counted and reported, never fails the gate
#   pending   NOT YET ANALYSED -- the gate cannot ship enforced while any row reads pending
"""


def die(msg: str) -> None:
    print(f"c16_roots_baseline.py: {msg}", file=sys.stderr)
    raise SystemExit(2)


def lake_roots() -> "list[str]":
    """The single scrape site every per-root sweep in this repository reads from."""

    def read(mode: str) -> "list[str]":
        out = subprocess.run(
            [sys.executable, os.path.join("scripts", "lake_targets.py"), mode],
            capture_output=True, text=True,
        )
        if out.returncode != 0:
            die(f"cannot enumerate {mode}: {out.stderr.strip()}")
        return [line for line in out.stdout.splitlines() if line]

    roots = read("exe-roots") + read("lib-roots")
    return [r for r in roots if r != "FormalSystem"]


def parse_log(text: str) -> "tuple[dict, bool]":
    """Returns ({(module, linter): count}, trusted).

    `trusted` is True only when the log carries a `-- Found N error(s)` or a
    `-- Linting passed for` line (Batteries' own two terminal shapes) AND every error line this
    parser saw was attributable to a (module, linter) pair. A log with neither shape, or with an
    error line outside any linter/module header, is untrustworthy -- the caller must treat that
    as exit 2, never as zero findings.
    """
    counts: "dict[tuple[str, str], int]" = {}
    cur_linter = None
    cur_module = None
    trusted = False
    for line in text.splitlines():
        if FOUND_RE.match(line) or PASSED_RE.match(line):
            trusted = True
            continue
        m = LINTER_HEADER_RE.match(line)
        if m:
            cur_linter = m.group(1)
            cur_module = None
            continue
        if ERROR_LINE_RE.match(line):
            if cur_linter is None or cur_module is None:
                trusted = False
                continue
            key = (cur_module, cur_linter)
            counts[key] = counts.get(key, 0) + 1
            continue
        m = MODULE_HEADER_RE.match(line)
        if m and cur_linter is not None:
            cur_module = m.group(1)
    return counts, trusted


def load_logs(log_dir: str, roots: "list[str]") -> "tuple[dict, list[tuple[str, str]]]":
    """Returns ({(root, module, linter): count}, [(root, problem), ...])."""
    live: "dict[tuple[str, str, str], int]" = {}
    problems: "list[tuple[str, str]]" = []
    for root in roots:
        path = os.path.join(log_dir, f"{root}.log")
        if not os.path.isfile(path):
            problems.append((root, f"missing log at {path}"))
            continue
        with open(path, encoding="utf-8", errors="replace") as fh:
            text = fh.read()
        counts, trusted = parse_log(text)
        if not trusted:
            problems.append((root, "unparseable log (no '-- Found ...' or "
                                    "'-- Linting passed for ...' line, or an error line outside "
                                    "any linter/module header)"))
            continue
        for (module, linter), c in counts.items():
            live[(root, module, linter)] = live.get((root, module, linter), 0) + c
    return live, problems


def load_unmeasurable(path: str) -> "dict[str, str]":
    """Returns {root: reason}, from the scripts/module-invariants-manifest.txt (C6) precedent:
    a root named here is excused from the anti-silence exit-2 guard below when its build or
    lint genuinely cannot be measured right now, for a reason recorded here -- never a silent
    pass, and never a substitute for fixing the root. A root's exclusion is reported on every
    run, not only granted once and forgotten; see the file's own header for the full contract."""
    out: "dict[str, str]" = {}
    if not os.path.isfile(path):
        return out
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            s = line.strip()
            if not s or s.startswith("#"):
                continue
            parts = s.split(None, 1)
            out[parts[0]] = parts[1] if len(parts) > 1 else ""
    return out


def parse_baseline(path: str) -> "tuple[dict, dict]":
    """Returns ({(root, module, linter): count}, {linter: disposition})."""
    entries: "dict[tuple[str, str, str], int]" = {}
    disp: "dict[str, str]" = {}
    if not os.path.isfile(path):
        return entries, disp
    with open(path, encoding="utf-8") as fh:
        for n, line in enumerate(fh, 1):
            s = line.strip()
            if not s:
                continue
            if s.startswith("# disposition "):
                parts = s[len("# disposition "):].split(None, 2)
                if len(parts) < 2 or parts[1] not in DISPOSITIONS:
                    die(f"{path}:{n}: malformed disposition row `{s}` "
                        f"(want `# disposition <linter> <{'|'.join(DISPOSITIONS)}> [reason]`)")
                disp[parts[0]] = parts[1]
                continue
            if s.startswith("#"):
                continue
            parts = s.split()
            if len(parts) != 4 or not parts[0].isdigit():
                die(f"{path}:{n}: malformed entry `{s}` "
                    "(want `<count> <root> <module> <linter>`)")
            cnt, root, module, linter = parts
            entries[(root, module, linter)] = int(cnt)
    return entries, disp


def render(live: "dict", disp: "dict") -> str:
    out = [HEADER.rstrip("\n")]
    for linter in sorted(disp):
        out.append(f"# disposition {linter} {disp[linter]}")
    total = sum(live.values())
    roots_dirty = len({r for r, _m, _l in live})
    out.append("#")
    out.append(f"# Baseline total: {total} finding(s) across {roots_dirty} root(s).")
    out.append("")
    for (root, module, linter), c in sorted(live.items()):
        out.append(f"{c} {root} {module} {linter}")
    return "\n".join(out) + "\n"


def main(argv: "list[str]") -> int:
    here = os.path.dirname(os.path.abspath(__file__))
    repo_root = os.path.dirname(here)
    ap = argparse.ArgumentParser(add_help=True, description=__doc__)
    ap.add_argument("--log-dir", required=True,
                     help="directory holding one <root>.log per non-FormalSystem lakefile root")
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--update", action="store_true")
    mode.add_argument("--list", action="store_true")
    try:
        args = ap.parse_args(argv)
    except SystemExit:
        return 2

    os.chdir(repo_root)
    baseline_path = BASELINE_NAME
    roots = lake_roots()
    live, problems = load_logs(args.log_dir, roots)
    unmeasurable = load_unmeasurable(UNMEASURABLE_NAME)
    excused = [(r, p) for r, p in problems if r in unmeasurable]
    unexcused = [(r, p) for r, p in problems if r not in unmeasurable]
    for r, p in excused:
        print(f"c16_roots_baseline.py: INFO  {r} excused via {UNMEASURABLE_NAME} "
              f"({unmeasurable[r]}) -- measured problem this run: {p}", file=sys.stderr)
    # A root listed as unmeasurable that measured CLEANLY this run is reported too -- a fixed
    # root earns its place back in the ceiling, it is never left excused by habit.
    stale_excuses = sorted(set(unmeasurable) - {r for r, _p in problems})
    for r in stale_excuses:
        print(f"c16_roots_baseline.py: INFO  {r} is listed in {UNMEASURABLE_NAME} but measured "
              "cleanly this run -- consider removing its row", file=sys.stderr)

    if args.list:
        if unexcused:
            die("untrusted measurement: " + "; ".join(f"{r}: {p}" for r, p in unexcused))
        for (root, module, linter), c in sorted(live.items(), key=lambda kv: -kv[1]):
            print(f"{c:5d}  {root}  {module}  {linter}")
        print(f"total: {sum(live.values())} finding(s) across "
              f"{len({r for r, _m, _l in live})} root(s)")
        return 0

    observed_classes = {linter for _r, _m, linter in live}

    if args.update:
        if unexcused:
            die("refusing to --update from an untrusted measurement: "
                + "; ".join(f"{r}: {p}" for r, p in unexcused))
        _old_entries, disp = parse_baseline(baseline_path)
        for k in observed_classes:
            disp.setdefault(k, "blocking")
        missing = sorted(observed_classes - set(disp))
        if missing:
            die("observed linter class(es) with no disposition row: " + ", ".join(missing))
        with open(baseline_path, "w", encoding="utf-8") as fh:
            fh.write(render(live, disp))
        dirty = len({r for r, _m, _l in live})
        measured = len(roots) - len(excused)
        print(f"c16_roots_baseline.py: wrote {baseline_path} -- "
              f"{sum(live.values())} finding(s) across {dirty} of {measured} measured root(s) "
              f"({len(excused)} of {len(roots)} total root(s) excused via {UNMEASURABLE_NAME})")
        return 0

    # Default: verify. An untrusted, UNEXCUSED measurement is an error, never silently treated
    # as zero findings. An excused root (see above) does not block the gate, but its exclusion
    # is reported on every run via the INFO lines above, not forgotten.
    if unexcused:
        print("c16_roots_baseline.py: FAIL -- measurement could not be trusted:", file=sys.stderr)
        for r, p in unexcused:
            print(f"  {r}: {p}", file=sys.stderr)
        return 2

    if not os.path.exists(baseline_path):
        die(f"{baseline_path} does not exist; run --update to create it")
    entries, disp = parse_baseline(baseline_path)

    missing = sorted(observed_classes - set(disp))
    if missing:
        die(
            f"observed linter class(es) with no disposition row in {BASELINE_NAME}: "
            + ", ".join(missing)
            + f". Read the class, decide {'/'.join(DISPOSITIONS)}, and add a `# disposition` "
            "row -- do not absorb it into the baseline with a routine --update."
        )

    pending = sorted(k for k in observed_classes if disp.get(k) == "pending")
    if pending:
        die(
            f"linter class(es) still marked `pending` in {BASELINE_NAME}: " + ", ".join(pending)
            + ". A pending class has not been read by anyone; decide blocking or advisory first."
        )

    failures = []
    for key, c in sorted(live.items()):
        linter = key[2]
        if disp.get(linter) == "advisory":
            continue
        base = entries.get(key)
        if base is None:
            failures.append(f"  NEW    {c:5d}  {key[0]}  {key[1]}  {linter}  (no baseline entry)")
        elif c > base:
            failures.append(f"  ABOVE  {c:5d}  {key[0]}  {key[1]}  {linter}  (baseline {base})")

    if failures:
        print(f"c16_roots_baseline.py: FAIL -- {len(failures)} entr(y/ies) above baseline")
        for f in failures:
            print(f)
        print(f"\nThe counts in {BASELINE_NAME} are a ceiling and may only decrease. Fix the "
              "finding, or -- if it is genuinely acceptable -- run --update and justify the "
              "diff in the same commit.")
        return 1

    below = [k for k in entries if live.get(k, 0) < entries[k]]
    total = sum(live.values())
    print(f"c16_roots_baseline.py: OK -- {total} finding(s) across "
          f"{len({r for r, _m, _l in live})} root(s), all at or below baseline"
          + (f" ({len(excused)} root(s) excused via {UNMEASURABLE_NAME})" if excused else ""))
    if below:
        print(f"  {len(below)} entr(y/ies) now below baseline; run --update to ratchet down")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
